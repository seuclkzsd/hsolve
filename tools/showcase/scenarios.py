def _reference(sc: Scenario, src: Path | None, root: Path) -> None:
    ref_dir = root / "refs" / sc.case
    if sc.reference == "source":
        src_ref = src.parent.parent / "refs" / src.name
        if not (src_ref / "eigenvalues.npy").exists():
            raise FileNotFoundError(f"{sc.id}: source case {src.name} has no reference")
        _symlink(src_ref, ref_dir)
    elif sc.reference == "arpack" and not (ref_dir / "eigenvalues.npy").exists():
        from tools.eval import reference
        print(reference.build_reference(sc.case, root), flush=True)
    elif sc.reference == "waveguide-family" and not (ref_dir / "eigenvalues.npy").exists():
        from tools.showcase import waveguide_ref
        print(waveguide_ref.write_reference(sc.case, root), flush=True)
    # "physical" and "generated" references are written with their case


def prepare_one(sc: Scenario, root: Path, source_roots: list[Path]) -> dict[str, Any]:
    """Build the scenario's case and reference under root; returns its resolved record."""
    case_dir = root / "cases" / sc.case
    src = find_source(sc.source, source_roots) if sc.source else None
    if sc.source is None:
        if not (case_dir / "A.npz").exists():
            GENERATORS[sc.case](root)
    elif sc.derived:
        if not (case_dir / "config.json").exists():
            if sc.reference != "physical":
                raise ValueError(f"{sc.id}: derived cases are written for physical references only")
            _write_physical_case(sc, src, root)
    else:
        _symlink(src, case_dir)
    _reference(sc, src, root)
    c = cio.load_case(sc.case, root=root)
    ref = cio.load_ref(sc.case, root=root)
    if isinstance(sc.target, str):
        if ref is None or not ref.info.get("complete") or ref.info.get("window") is not None:
            raise ValueError(f"{sc.id}: resolver {sc.target} needs a complete whole-spectrum reference")
        target = RESOLVERS[sc.target](c, np.asarray(ref.eigenvalues, dtype=float).real)
        override = True
    elif isinstance(sc.target, dict):
        target, override = dict(sc.target), True
    else:
        target, override = dict(c.config["target"]), False
    # Resolvers may add facts about the target (the eigenvalue sigma sits on, an interval's count);
    # the solvers get the SolverConfig target keys only (hsolve rejects unknown keys).
    target_info = {k: v for k, v in target.items() if k not in TARGET_KEYS}
    target = {k: v for k, v in target.items() if k in TARGET_KEYS}
    rec = asdict(sc)
    rec.update(group_label=GROUPS[sc.group], target=target, target_info=target_info, override=override,
               hsolve_config=hsolve_keys(sc, c.meta["problem"]), n=c.n, problem=c.meta["problem"],
               dtype=c.meta.get("dtype"), nnz_a=int(c.A.nnz), nnz_b=int(c.B.nnz) if c.B is not None else 0,
               source_path=str(src) if src else None,
               reference_info=None if ref is None else {**ref.info, "count": int(ref.eigenvalues.size)})
    if target.get("mode", "nearest") == "nearest" and ref is not None and ref.info.get("complete") \
            and ref.info.get("window") is None:
        rec["target_multiplicities"] = target_multiplicities(np.asarray(ref.eigenvalues).real, target)
    return rec


def load_resolved(root: Path) -> dict[str, dict[str, Any]]:
    path = Path(root) / RESOLVED_FILE
    return json.loads(path.read_text())["scenarios"] if path.exists() else {}


def prepare(root: Path, source_roots: list[Path], ids: list[str] | None = None) -> dict[str, dict[str, Any]]:
    root = Path(root)
    (root / "cases").mkdir(parents=True, exist_ok=True)
    (root / "refs").mkdir(parents=True, exist_ok=True)
    resolved = load_resolved(root)
    for sc in by_id(ids):
        rec = prepare_one(sc, root, [Path(r).resolve() for r in source_roots])
        resolved[sc.id] = rec
        print(json.dumps({"scenario": sc.id, "case": sc.case, "n": rec["n"], "target": rec["target"],
                          "reference": (rec["reference_info"] or {}).get("kind")}), flush=True)
    order = [s.id for s in SCENARIOS]
    doc = {"schema_version": 1, "root": str(root),
           "scenarios": {k: resolved[k] for k in sorted(resolved, key=order.index)}}
    tmp = root / (RESOLVED_FILE + ".tmp")
    tmp.write_text(json.dumps(doc, indent=1, ensure_ascii=False) + "\n")
    shutil.move(tmp, root / RESOLVED_FILE)
    return doc["scenarios"]


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    sub.add_parser("list", help="print the catalogue")
    p = sub.add_parser("prepare", help="build the campaign data root")
    p.add_argument("--root", type=Path, default=DEFAULT_ROOT)
    p.add_argument("--source-root", type=Path, action="append", default=None,
                   help="where source cases live (repeatable; default: the repository's data/)")
    p.add_argument("--only", nargs="+", default=None, help="scenario ids (default: all)")
    args = ap.parse_args(argv)
    if args.cmd == "list":
        for s in SCENARIOS:
            print(f"{s.id:22s} {GROUPS[s.group]:14s} {s.case:28s} {s.title}")
        return 0
    from tools.eval import common
    common.require_guard("showcase.scenarios")
    prepare(args.root, args.source_root or [cio.DEFAULT_ROOT], args.only)
    return 0


