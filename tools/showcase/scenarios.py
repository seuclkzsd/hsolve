def by_id(ids: list[str] | None = None) -> list[Scenario]:
    """The scenarios with these ids (all when None), in catalogue order; unknown ids are an error."""
    known = {s.id: s for s in SCENARIOS}
    if ids is None:
        return list(SCENARIOS)
    unknown = [i for i in ids if i not in known]
    if unknown:
        raise SystemExit(f"unknown scenario(s) {', '.join(unknown)} (known: {', '.join(known)})")
    return [s for s in SCENARIOS if s.id in set(ids)]


def hsolve_keys(sc: Scenario, problem: str) -> dict[str, Any]:
    """Configuration keys hsolve gets on top of the case config (the fast path off, see above)."""
    pin = dict(METHOD_PIN) if problem in ("HEP", "GHEP") else {}
    return {**pin, **sc.hsolve}


