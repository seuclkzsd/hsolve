def find_source(name: str, source_roots: list[Path]) -> Path:
    for r in source_roots:
        p = Path(r) / "cases" / name
        if (p / "A.npz").exists():
            return p
    raise FileNotFoundError(f"source case {name} not found under {', '.join(map(str, source_roots))}")


def _symlink(src: Path, dst: Path) -> None:
    """dst -> src; an existing link to the same place is kept, anything else is an error."""
    if dst.is_symlink() and Path(os.readlink(dst)) == src:
        return
    if dst.exists() or dst.is_symlink():
        raise FileExistsError(f"{dst} exists and is not a link to {src} (remove it or use another root)")
    dst.parent.mkdir(parents=True, exist_ok=True)
    dst.symlink_to(src)


def _write_physical_case(sc: Scenario, src: Path, root: Path) -> None:
    """A case directory sharing the source matrices, asking for physical modes: the target is the
    lowest k nonzero eigenvalues (sigma = 0), the reference lists the spectrum without the null
    space (the zero level of a curl-curl pencil is not a resonance)."""
    out = root / "cases" / sc.case
    out.mkdir(parents=True, exist_ok=True)
    for f in ("A.npz", "B.npz"):
        if (src / f).exists():
            _symlink(src / f, out / f)
    c = cio.load_case(src)
    ref = cio.load_ref(src.name, root=src.parent.parent)
    if ref is None or not ref.info.get("complete") or ref.info.get("window") is not None:
        raise ValueError(f"{sc.id}: the source needs a complete whole-spectrum reference")
    w = np.asarray(ref.eigenvalues, dtype=float)
    zero = np.abs(w) <= 1e-12 * np.abs(w).max()
    physical = w[~zero]
    target = lowest_physical_target(physical, cond_b=diagonal_cond(c.B))
    meta = dict(c.meta)
    meta.update(name=sc.case, derived_from=src.name,
                description=f"{c.meta.get('description', '')}; physical modes only: the "
                            f"{int(zero.sum())}-dimensional gradient null space (eigenvalue 0) is not wanted")
    meta.pop("targets", None)
    (out / "meta.json").write_text(json.dumps(meta, indent=2, ensure_ascii=False) + "\n")
    (out / "config.json").write_text(json.dumps({"target": target, "tol": TOL}, indent=2) + "\n")
    cio.save_ref(sc.case, physical, kind="discrete-exact", complete=True, window=None, root=root,
                 note=(f"physical spectrum of {src.name}: its exact discrete spectrum without the "
                       f"{int(zero.sum())} zero eigenvalues of the gradient null space (not resonances); "
                       "a returned null-space vector is therefore spurious for this case"))


