@dataclass(frozen=True)
class Scenario:
    """One campaign row. target: None = the case config's target; a dict = that target; a string =
    the name of a resolver in RESOLVERS, evaluated on the case's exact reference by `prepare`."""
    id: str
    group: str
    title: str                    # one line, shown in the tables
    case: str                     # case directory name in the campaign root
    source: str | None            # source case (None: generated by GENERATORS[case])
    why: str                      # what makes the scenario hard
