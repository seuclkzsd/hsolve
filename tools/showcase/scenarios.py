def distinct_levels(eigenvalues, rtol: float = 1e-9) -> tuple[np.ndarray, np.ndarray]:
    from tools.gen.synthetic import distinct_levels as levels
    return levels(eigenvalues, rtol)


def nearest_k(eigenvalues, sigma: float, k_min: int, cond_b: float = 1.0) -> int:
    from tools.gen.synthetic import nearest_k_closed
    return nearest_k_closed(eigenvalues, sigma, k_min, cond_b=cond_b, tol=TOL)


def physical_levels(eigenvalues) -> tuple[np.ndarray, np.ndarray]:
    """Distinct positive levels (the physical resonances of a curl-curl spectrum) and multiplicities."""
    lev, cnt = distinct_levels(eigenvalues)
    keep = lev > 0
    return lev[keep], cnt[keep]


def multiplet_target(eigenvalues, want=(3, 6, 12), k_min: int = 12, frac: float = 0.4,
                     search: int = 200, cond_b: float = 1.0) -> dict[str, Any]:
    """Smallest decidable 'nearest k' target whose set consists of whole multiplets including one
    of each multiplicity in `want` (a cubic PEC cavity has 3-, 6- and 12-fold levels). sigma sits
    at `frac` of a gap between consecutive physical levels (never at a midpoint, where both
    neighbours would tie); targets reaching down to the null space are skipped."""
    w = np.asarray(eigenvalues, dtype=float)
    lev, cnt = physical_levels(w)
    best: tuple[int, float] | None = None
    for i in range(min(search, lev.size - 1)):
        sigma = float(lev[i] + frac * (lev[i + 1] - lev[i]))
        seen: set[int] = set()
        k = 0
        for j in np.argsort(np.abs(lev - sigma), kind="stable"):
            k += int(cnt[j])
            seen.add(int(cnt[j]))
            if set(want) <= seen and k >= k_min:
                break
        else:
            continue
        k = nearest_k(w, sigma, k, cond_b)
        if np.sort(np.abs(w - sigma))[k - 1] >= sigma:   # the set would reach the zero level
            continue
        if best is None or k < best[0]:
            best = (k, sigma)
    if best is None:
        raise ValueError(f"no decidable target with multiplicities {want} among the first {search} levels")
    k, sigma = best
    return {"mode": "nearest", "sigma": sigma, "k": int(k)}


def target_multiplicities(eigenvalues, target: dict[str, Any]) -> list[int]:
    """Multiplicities of the levels in a nearest target's set, ascending by level."""
    w = np.asarray(eigenvalues, dtype=float)
    chosen = np.sort(w[np.argsort(np.abs(w - float(target["sigma"])), kind="stable")[:int(target["k"])]])
    _, cnt = distinct_levels(chosen)
    return [int(c) for c in cnt]


def on_eigenvalue_target(eigenvalues, sigma_hint: float, rel_offset: float = 0.0, k_min: int = 10,
                         cond_b: float = 1.0) -> dict[str, Any]:
    """sigma = (1 + rel_offset) * the physical level nearest sigma_hint (rel_offset = 0: sigma is the
    eigenvalue itself, K = A - sigma B singular up to rounding); smallest decidable k >= k_min."""
    w = np.asarray(eigenvalues, dtype=float)
    lev, _ = physical_levels(w)
    level = float(lev[np.argmin(np.abs(lev - sigma_hint))])
    sigma = level * (1.0 + rel_offset)
    return {"mode": "nearest", "sigma": sigma, "k": int(nearest_k(w, sigma, k_min, cond_b)),
            "eigenvalue": level}


def lowest_physical_target(physical, k_min: int = 10, cond_b: float = 1.0) -> dict[str, Any]:
    """sigma = 0 over the physical spectrum: the lowest k resonances (k decidable)."""
    w = np.asarray(physical, dtype=float)
    return {"mode": "nearest", "sigma": 0.0, "k": int(nearest_k(w, 0.0, k_min, cond_b))}


def interval_target(eigenvalues, first_level: int, count_min: int) -> dict[str, Any]:
    """[lower, upper] at the midpoints of the gaps around physical levels first_level..j, with j the
    first level at which the interval holds >= count_min eigenvalues."""
    lev, cnt = physical_levels(eigenvalues)
    if not 1 <= first_level < lev.size - 1:
        raise ValueError(f"first_level {first_level} outside [1, {lev.size - 2}]")
    total = 0
    for j in range(first_level, lev.size - 1):
        total += int(cnt[j])
        if total >= count_min:
            return {"mode": "interval", "lower": float(0.5 * (lev[first_level - 1] + lev[first_level])),
                    "upper": float(0.5 * (lev[j] + lev[j + 1])), "count": total}
    raise ValueError("spectrum too short for the interval")


def diagonal_cond(b) -> float:
    """cond(B) of a diagonal HPD B (1 for B = None)."""
    if b is None:
        return 1.0
    d = np.abs(b.diagonal())
    if b.nnz != b.shape[0] or d.min() <= 0:
        raise ValueError("diagonal_cond needs a diagonal HPD B")
    return float(d.max() / d.min())


